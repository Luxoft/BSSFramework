using System.Runtime.CompilerServices;

using Anch.Core.Auth;

using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.ChangeTracking;
using Microsoft.EntityFrameworkCore.Diagnostics;
using Microsoft.EntityFrameworkCore.Infrastructure;
using Microsoft.Extensions.DependencyInjection;

namespace Framework.Database.EntityFramework.EnversAudit;

/// <summary>
/// Emulates NHibernate.Envers on top of EF Core: writes audit rows and a revision for every save.
/// Works in two phases around one <c>SaveChanges</c> call:
/// <list type="number">
///     <item>SavingChanges - snapshot the change tracker into <see cref="AuditEntry"/> list (before EF resets entry states);</item>
///     <item>SavedChanges - create the revision and audit entities from the snapshot and call <c>SaveChanges</c> a second time.</item>
/// </list>
/// The nested <c>SaveChanges</c> re-enters this interceptor, but does not recurse: audit entity types are never registered
/// in <see cref="IAuditEntityFactory"/> as source types, so <see cref="CreateAuditEntries"/> yields nothing for them,
/// no snapshot is stored and <see cref="WriteAudits"/> exits early.
/// Pending snapshots are keyed by <see cref="DbContext"/> instance, so the same interceptor instance may serve several contexts.
/// </summary>
public class AuditFlushInterceptor : SaveChangesInterceptor
{
    private readonly ConditionalWeakTable<DbContext, List<AuditEntry>> pendingAudits = [];

    public override InterceptionResult<int> SavingChanges(
        DbContextEventData eventData,
        InterceptionResult<int> result)
    {
        this.CaptureChanges(eventData.Context);
        return base.SavingChanges(eventData, result);
    }

    public override ValueTask<InterceptionResult<int>> SavingChangesAsync(
        DbContextEventData eventData,
        InterceptionResult<int> result,
        CancellationToken ct)
    {
        this.CaptureChanges(eventData.Context);
        return base.SavingChangesAsync(eventData, result, ct);
    }

    public override int SavedChanges(SaveChangesCompletedEventData eventData, int result)
    {
        this.WriteAudits(eventData.Context);
        return base.SavedChanges(eventData, result);
    }

    public override async ValueTask<int> SavedChangesAsync(
        SaveChangesCompletedEventData eventData,
        int result,
        CancellationToken ct)
    {
        await this.WriteAuditsAsync(eventData.Context, ct);
        return await base.SavedChangesAsync(eventData, result, ct);
    }

    private void CaptureChanges(DbContext? dbContext)
    {
        if (dbContext is null)
        {
            return;
        }

        var auditEntityFactory = dbContext.GetService<IAuditEntityFactory>();
        var audits = dbContext.ChangeTracker.Entries()
                              .Where(entry => entry.State is EntityState.Added or EntityState.Modified or EntityState.Deleted)
                              .SelectMany(entry => this.CreateAuditEntries(entry, auditEntityFactory))
                              .ToList();

        if (audits.Count > 0)
        {
            // Last snapshot wins: a failed SaveChanges leaves a stale snapshot behind which must not be mixed with the retry.
            this.pendingAudits.Remove(dbContext);
            this.pendingAudits.Add(dbContext, audits);
        }
    }

    private void WriteAudits(DbContext? dbContext)
    {
        if (dbContext is null
            || !this.pendingAudits.TryGetValue(dbContext, out var audits)
            || dbContext is not IEnversAuditDbContext auditableDbContext)
        {
            return;
        }

        // Remove before the nested SaveChanges so a re-entrant SavedChanges can't write the same snapshot twice.
        this.pendingAudits.Remove(dbContext);
        var revision = this.AddAuditEntities(dbContext, auditableDbContext, audits, dbContext.GetService<IAuditEntityFactory>());
        dbContext.SaveChanges();

        // Revision.Id is generated by the database, so it is only known after the nested SaveChanges.
        auditableDbContext.ServiceProvider.GetRequiredService<EfCurrentRevisionState>().CurrentRevision = revision.Id;
    }

    private async Task WriteAuditsAsync(DbContext? dbContext, CancellationToken ct)
    {
        if (dbContext is null
            || !this.pendingAudits.TryGetValue(dbContext, out var audits)
            || dbContext is not IEnversAuditDbContext auditableDbContext)
        {
            return;
        }

        this.pendingAudits.Remove(dbContext);
        var revision = this.AddAuditEntities(dbContext, auditableDbContext, audits, dbContext.GetService<IAuditEntityFactory>());
        await dbContext.SaveChangesAsync(ct);

        auditableDbContext.ServiceProvider.GetRequiredService<EfCurrentRevisionState>().CurrentRevision = revision.Id;
    }

    private IEnumerable<AuditEntry> CreateAuditEntries(EntityEntry entry, IAuditEntityFactory auditEntityFactory)
    {
        // NHibernate.Envers writes one audit row per level of a TPT hierarchy (e.g. CompanyLegalEntityAudit and LegalEntityBaseAudit);
        // walk the CLR base-type chain so EF mirrors that instead of auditing only the leaf entity type.
        for (var type = entry.Metadata.ClrType; type != null; type = type.BaseType)
        {
            if (!auditEntityFactory.TryGet(type, out var metadata))
            {
                continue;
            }

            var modifiedProperties = metadata.Properties
                                             .Where(property => !property.IsKey)
                                             .ToDictionary(
                                                 property => property.Name,
                                                 property => this.IsPropertyModified(entry, property));

            yield return new AuditEntry(entry, metadata, this.ToRevisionType(entry.State), modifiedProperties);
        }
    }

    private AuditRevisionEntity AddAuditEntities(
        DbContext dbContext,
        IEnversAuditDbContext auditableDbContext,
        List<AuditEntry> audits,
        IAuditEntityFactory auditEntityFactory)
    {
        var revision = new AuditRevisionEntity
                       {
                           RevisionDate = DateTime.SpecifyKind(auditableDbContext.ServiceProvider.GetRequiredService<TimeProvider>().GetUtcNow().DateTime, DateTimeKind.Utc),
                           Author = auditableDbContext.ServiceProvider.GetRequiredService<ICurrentUser>().Name
                       };
        dbContext.Set<AuditRevisionEntity>().Add(revision);

        foreach (var audit in audits)
        {
            var auditEntity = Activator.CreateInstance(audit.Metadata.AuditEntityType)!;
            foreach (var property in audit.Metadata.Properties)
            {
                if (!property.IsModOnly)
                {
                    // Mirrors NHibernate.Envers StoreDataAtDelete = false: no field snapshot is kept on the delete revision.
                    var value = audit.RevisionType == AuditRevisionType.Deleted && !property.IsKey
                                    ? null
                                    : this.GetCurrentValue(audit.Entry, property);

                    audit.Metadata.AuditEntityType.GetProperty(property.Name)!.SetValue(auditEntity, value);
                }

                if (!property.IsKey)
                {
                    audit.Metadata.AuditEntityType.GetProperty($"{property.ModName}_MOD")!
                         .SetValue(auditEntity, audit.ModifiedProperties[property.Name]);
                }
            }

            audit.Metadata.AuditEntityType
                 .GetProperty(auditEntityFactory.RevisionPropertyName)!
                 .SetValue(auditEntity, revision);
            audit.Metadata.AuditEntityType
                 .GetProperty(auditEntityFactory.RevisionTypePropertyName)!
                 .SetValue(auditEntity, audit.RevisionType);
            dbContext.Add(auditEntity);
        }

        return revision;
    }

    private AuditRevisionType ToRevisionType(EntityState state) => state switch
    {
        EntityState.Added => AuditRevisionType.Added,
        EntityState.Modified => AuditRevisionType.Modified,
        EntityState.Deleted => AuditRevisionType.Deleted,
        _ => throw new ArgumentOutOfRangeException(nameof(state), state, null)
    };

    private bool IsPropertyModified(EntityEntry entry, AuditPropertyMetadata property) =>
        entry.State == EntityState.Added
        || entry.State == EntityState.Modified && !property.IsModOnly && this.GetPropertyEntry(entry, property) is { IsModified: true };

    private object? GetCurrentValue(EntityEntry entry, AuditPropertyMetadata property) =>
        this.GetPropertyEntry(entry, property)?.CurrentValue;

    private PropertyEntry? GetPropertyEntry(EntityEntry entry, AuditPropertyMetadata property)
    {
        if (property.NestedPropertyName is null)
        {
            return entry.Property(property.EntryPropertyName ?? property.Name);
        }

        if (property.IsOwned)
        {
            var targetEntry = entry.Reference(property.ModName).TargetEntry;
            return targetEntry?.Property(property.NestedPropertyName);
        }

        return entry.ComplexProperty(property.ModName).Property(property.NestedPropertyName);
    }

    private sealed record AuditEntry(
        EntityEntry Entry,
        AuditEntityMetadata Metadata,
        AuditRevisionType RevisionType,
        IReadOnlyDictionary<string, bool> ModifiedProperties);
}
